#!/bin/bash
# Writes Vendor/engine.xcconfig: framework/library search paths, header
# paths and link flags for every xcframework in Vendor/Frameworks (iOS
# device slice), plus the system libraries libmpv/FFmpeg/MoltenVK need.
set -euo pipefail
cd "$(dirname "$0")/.."
FW=Vendor/Frameworks
OUT=Vendor/engine.xcconfig
fsp=(); lsp=(); hsp=(); ld=()
for x in "$FW"/*.xcframework; do
  slice=$(ls -d "$x"/ios-arm64 2>/dev/null || true)
  [ -z "$slice" ] && slice=$(ls -d "$x"/ios-arm64* 2>/dev/null | grep -v simulator | grep -v maccatalyst | head -1 || true)
  [ -z "$slice" ] && { echo "warning: no iOS slice in $x" >&2; continue; }
  rel="\$(PROJECT_DIR)/$slice"
  if ls -d "$slice"/*.framework >/dev/null 2>&1; then
    for f in "$slice"/*.framework; do
      name=$(basename "$f" .framework)
      fsp+=("\"$rel\""); ld+=("-framework" "$name")
      [ -d "$f/Headers" ] && hsp+=("\"$rel/$name.framework/Headers\"")
    done
  fi
  for a in "$slice"/lib*.a; do
    [ -e "$a" ] || continue
    name=$(basename "$a" .a); name=${name#lib}
    lsp+=("\"$rel\""); ld+=("-l$name")
  done
  [ -d "$slice/Headers" ] && hsp+=("\"$rel/Headers\"")
done
uniq_join() { printf '%s\n' "$@" | awk '!seen[$0]++' | tr '\n' ' '; }
{
  echo "// Generated by scripts/engine-xcconfig.sh — do not edit"
  echo "FRAMEWORK_SEARCH_PATHS = \$(inherited) $(uniq_join "${fsp[@]}")"
  echo "LIBRARY_SEARCH_PATHS = \$(inherited) $(uniq_join "${lsp[@]:-}")"
  echo "HEADER_SEARCH_PATHS = \$(inherited) $(uniq_join "${hsp[@]}")"
  echo "OTHER_LDFLAGS = \$(inherited) ${ld[*]} -lz -lbz2 -liconv -lc++ -lxml2 -lexpat -lresolv -framework Metal -framework IOSurface -framework QuartzCore -framework CoreVideo -framework CoreMedia -framework VideoToolbox -framework AudioToolbox -framework AVFoundation -framework CoreAudio -framework CoreText -framework CoreGraphics -framework CoreFoundation -framework Security -framework OpenGLES"
} > "$OUT"
cat "$OUT"
